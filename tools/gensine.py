#!/usr/bin/env python3
"""Emit sine_table.h: one period of sine as 256 unsigned 8-bit samples.

Centered on 128 with peak 127, so table[i] + table[i + 128] == 256 and
the waveform has no DC offset. Python's round() is half-to-even, which
is symmetric under negation; that symmetry is what the test checks.
"""
import math

vals = [128 + round(127 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
print("/* SPDX-License-Identifier: LicenseRef-PublicDomain */")
print("/* Generated by tools/gensine.py. Do not edit. */")
print("#ifndef WAVEGEN_SINE_TABLE_H")
print("#define WAVEGEN_SINE_TABLE_H")
print("static const u8 wg_sine_table[256] = {")
for row in range(0, 256, 12):
    print("\t" + " ".join(f"{v:3d}," for v in vals[row:row + 12]))
print("};")
print("#endif")
